<#
.SYNOPSIS
    CleanYourPhone - Safe Debloat Execution Script for Windows PowerShell
.DESCRIPTION
    Disables or uninstalls bloatware packages for User 0 over ADB.
    Includes strict core package blacklist protection, automated pre-backup,
    and automatic undo restore script generation.
.EXAMPLE
    .\tools\disable.ps1 -List "lists\oppo\coloros-safe-debloat.txt"
    .\tools\disable.ps1 -List "lists\oppo\coloros-safe-debloat.txt" -Mode "uninstall"
    .\tools\disable.ps1 -List "lists\oppo\coloros-safe-debloat.txt" -DryRun
#>

param (
    [Parameter(Mandatory = $true, Position = 0)]
    [string]$List,

    [ValidateSet("disable", "uninstall")]
    [string]$Mode = "disable",

    [switch]$DryRun,
    [switch]$InstallLauncher,
    [switch]$KeepLauncher
)

$ErrorActionPreference = "Stop"

if (-not (Test-Path -Path $List)) {
    Write-Error "Error: Package list file not found: $List"
    exit 1
}

# Check for ADB
$adbCmd = Get-Command "adb" -ErrorAction SilentlyContinue
if (-not $adbCmd) {
    Write-Error "Error: 'adb' executable not found in PATH. Install Android platform-tools."
    exit 1
}

# Verify device
$devices = adb devices
$attached = ($devices | Select-String -Pattern "\s+device$")
if (-not $attached) {
    Write-Error "Error: No Android device detected over ADB. Check USB connection or run 'adb connect <ip>:5555'."
    exit 1
}

$brand = (adb shell getprop ro.product.brand).Trim()
$model = (adb shell getprop ro.product.model).Trim()

Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host " Connected Device: $brand $model" -ForegroundColor Green
Write-Host " Debloat Mode    : $Mode (User 0 only)" -ForegroundColor White
if ($DryRun) {
    Write-Host " Execution Mode  : DRY RUN (no modifications will be made)" -ForegroundColor Yellow
}
Write-Host "==========================================================" -ForegroundColor Cyan

# Read and clean list
$rawLines = Get-Content -Path $List -Encoding UTF8
$pkgs = @()
foreach ($line in $rawLines) {
    $clean = $line.Trim()
    if ($clean.StartsWith("#") -or [string]::IsNullOrWhiteSpace($clean)) {
        continue
    }
    # Strip inline comments
    $pkgName = ($clean -split "#")[0].Trim()
    if ($pkgName) {
        $pkgs += $pkgName
    }
}

if ($pkgs.Count -eq 0) {
    Write-Error "Error: No valid packages found in $List."
    exit 1
}

# Package regex
$pkgRegex = "^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z0-9_]+)+$"
foreach ($p in $pkgs) {
    if ($p -notmatch $pkgRegex) {
        Write-Error "Error: Invalid package name format: '$p'"
        exit 1
    }
}

# Core Android package blacklist regex
$coreRegex = "^(android|android\.ext\.(services|shared)|com\.android\.sdksandbox|com\.android\.location\.fused|com\.android\.systemui|com\.android\.shell|com\.android\.phone|com\.android\.dialer|com\.android\.server\.telecom|com\.android\.settings|com\.android\.keyguard|com\.(google\.)?android\.(permissioncontroller|packageinstaller|ext\.services|ext\.shared|modulemetadata)|com\.google\.android\.overlay\.modules.*|com\.android\.providers\.(telephony|media|downloads|settings)|com\.qualcomm\.qti\.telephonyservice|com\.mediatek\.telephony)$"

$coreViolations = $pkgs | Where-Object { $_ -match $coreRegex }
if ($coreViolations) {
    Write-Host "CRITICAL SAFETY REFUSAL: The list contains protected core Android packages:" -ForegroundColor Red
    $coreViolations | ForEach-Object { Write-Host "  $_" -ForegroundColor Red }
    Write-Error "Debloat aborted to protect system stability."
    exit 1
}

# Create backup
$timestamp = Get-Date -Format "yyyyMMdd_HHmmss"
$backupDir = "backups\backup_$timestamp"
New-Item -ItemType Directory -Force -Path $backupDir | Out-Null

Write-Host "[*] Creating safety backup in $backupDir..." -ForegroundColor DarkGray
adb shell pm list packages -f | Out-File -FilePath "$backupDir\installed_packages.txt" -Encoding utf8
adb shell pm list packages -d | Out-File -FilePath "$backupDir\disabled_packages.txt" -Encoding utf8
adb shell getprop | Out-File -FilePath "$backupDir\getprop.txt" -Encoding utf8

$restorePs1 = "$backupDir\restore.ps1"
@"
# Automated restore script generated by CleanYourPhone
Write-Host "Restoring packages..." -ForegroundColor Cyan
"@ | Out-File -FilePath $restorePs1 -Encoding utf8

# Cache installed packages
$installedRaw = adb shell pm list packages
$installedCache = @{}
foreach ($item in $installedRaw) {
    $cleanItem = $item.Trim()
    if ($cleanItem.StartsWith("package:")) {
        $installedCache[$cleanItem.Substring(8)] = $true
    }
}

$total = $pkgs.Count
$current = 0
$removed = 0
$skipped = 0

Write-Host "[*] Processing $total packages..." -ForegroundColor White

foreach ($pkg in $pkgs) {
    $current++

    if (-not $installedCache.ContainsKey($pkg)) {
        Write-Host "[$current/$total] Skipped: $pkg (not installed)" -ForegroundColor DarkGray
        $skipped++
        continue
    }

    if ($DryRun) {
        Write-Host "[$current/$total] [DRY RUN] Would $Mode: $pkg" -ForegroundColor Yellow
        continue
    }

    if ($Mode -eq "uninstall") {
        "adb shell cmd package install-existing $pkg | Out-Null; adb shell pm enable $pkg | Out-Null" | Out-File -FilePath $restorePs1 -Append -Encoding utf8
        $res = adb shell pm uninstall -k --user 0 $pkg 2>&1
        if ($res -match "Success") {
            Write-Host "[$current/$total] Uninstalled: $pkg" -ForegroundColor Green
            $removed++
        } else {
            Write-Host "[$current/$total] Uninstall failed. Falling back to disable..." -ForegroundColor Yellow
            adb shell pm disable-user --user 0 $pkg | Out-Null
            Write-Host "[$current/$total] Disabled: $pkg" -ForegroundColor Green
            $removed++
        }
    } else {
        "adb shell pm enable $pkg | Out-Null" | Out-File -FilePath $restorePs1 -Append -Encoding utf8
        adb shell pm disable-user --user 0 $pkg | Out-Null
        Write-Host "[$current/$total] Disabled: $pkg" -ForegroundColor Green
        $removed++
    }
}

@"
Write-Host "Restore complete." -ForegroundColor Green
"@ | Out-File -FilePath $restorePs1 -Append -Encoding utf8

Copy-Item -Path $restorePs1 -Destination "restore_last_session.ps1" -Force

Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host " Debloat Completed Successfully!" -ForegroundColor Green
Write-Host " Total examined : $total"
Write-Host " Removed/Disabled: $removed"
Write-Host " Already absent : $skipped"
Write-Host " Restore script : .\restore_last_session.ps1" -ForegroundColor Yellow
Write-Host " Backup snapshot: $backupDir\" -ForegroundColor DarkGray
Write-Host "==========================================================" -ForegroundColor Cyan

# Stage 2: Minimalist Home Screen Selection
if (-not $DryRun) {
    Write-Host ""
    Write-Host "==========================================================" -ForegroundColor Cyan
    Write-Host " Stage 2: Minimalist Home Screen Upgrade" -ForegroundColor Green
    Write-Host "==========================================================" -ForegroundColor Cyan
    Write-Host "CleanYourPhone includes a minimal Apple-like Liquid Glass Launcher"
    Write-Host "(ultra-lightweight, frosted dock, zero ads, <15MB RAM)."
    Write-Host ""

    if (-not $InstallLauncher -and -not $KeepLauncher) {
        $choice = Read-Host "Would you like to install the Liquid Glass Launcher? [y/N]"
        if ($choice -match "^[Yy]$") {
            $InstallLauncher = $true
        }
    }

    if ($InstallLauncher) {
        Write-Host "[*] Launching installer..." -ForegroundColor Cyan
        & ".\launcher\build-and-install.ps1"
    } else {
        Write-Host "[*] Keeping your existing home screen." -ForegroundColor White
    }
}
